// node --test tools/design-inventory.test.mjs
import test from 'node:test'
import assert from 'node:assert/strict'
import { mkdtempSync, mkdirSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { scan, render, literalsIn, codeLines } from './design-inventory.mjs'

function fixture() {
  const root = mkdtempSync(join(tmpdir(), 'di-'))
  for (const d of ['UI', 'Trips', 'Debug']) mkdirSync(join(root, d))
  writeFileSync(join(root, 'UI/Theme.swift'), 'struct Shared: View {\n  var body: some View { Text("x").font(.system(size: 99)) }\n}\nlet c = Color(white: 0.5)\n')
  writeFileSync(join(root, 'Trips/A.swift'), `struct Once: View { var body: some View { Text("a").font(.system(size: 14)).padding(8).opacity(0.5) } }
struct Twice: ViewModifier { func body(content: Content) -> some View { content.padding(.horizontal, 14).frame(width: 44, height: 44) } }
// .font(.system(size: 77))
#Preview {
  Text("p").font(.system(size: 55))
}
let a = Color(hex: "#2563eb"), b = Color(red: 1, green: 0, blue: 0)
`)
  writeFileSync(join(root, 'Trips/B.swift'), 'struct Uses: View { var body: some View { Twice().modifier(Twice()).font(.system(size: 14)).cornerRadius(6) } }\n')
  writeFileSync(join(root, 'Debug/DesignInventory.swift'), 'Once Twice')
  return root
}

test('views: counts other files that mention each, skips UI/ and previews', () => {
  const { views } = scan(fixture())
  const by = Object.fromEntries(views.map((v) => [v.name, v]))
  assert.deepEqual(Object.keys(by).sort(), ['Once', 'Twice', 'Uses'])
  assert.equal(by.Once.usedIn, 0)
  assert.equal(by.Twice.usedIn, 1)
  assert.equal(by.Twice.kind, 'ViewModifier')
})

test('literals: values, grouping inputs, comments and previews skipped', () => {
  const { literals } = scan(fixture())
  const fonts = literals.filter((l) => l.category === 'font')
  assert.deepEqual(fonts.map((l) => `${l.value}@${l.file}:${l.line}`), ['14@Trips/A.swift:1', '14@Trips/B.swift:1', '99@UI/Theme.swift:2'])
  const colors = literals.filter((l) => l.category === 'color').map((l) => l.value)
  assert.deepEqual(colors, ['#2563EB', 'red 1, green 0, blue 0'])
  assert.ok(literals.some((l) => l.category === 'padding' && l.value === '14'))
  assert.ok(literals.some((l) => l.category === 'frame' && l.value === 'width 44, height 44'))
  assert.ok(literals.some((l) => l.category === 'radius' && l.value === '6'))
})

test('render is deterministic and --check text matches', () => {
  const root = fixture()
  assert.equal(render(scan(root)), render(scan(root)))
  assert.match(render(scan(root)), /GENERATED by tools\/design-inventory.mjs/)
})

test('literalsIn reads several per line and ignores variables', () => {
  assert.equal(literalsIn('.padding(x).font(.system(size: size))', 'A.swift').length, 0)
  assert.equal(literalsIn('.padding(.top, 4).padding(6)', 'A.swift').length, 2)
  assert.equal(codeLines('a // .opacity(0.3)')[0].includes('opacity'), false)
})
